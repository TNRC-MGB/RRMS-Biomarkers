# ==============================================================================
# (b) GWAS summary statistics -> MAGMA p-value file
# ==============================================================================
# MAGMA wants a plain table with a SNP id column and a p-value column. The
# per-SNP sample size is carried through as N; the gene-analysis step in
# 02_magma.sh passes N = 41505 explicitly.
#
# MS.final.txt holds MS GWAS summary statistics generated by the International
# Multiple Sclerosis Genetics Consortium (https://doi.org/10.1126/science.aav7188)
# and obtained from the consortium. They are not redistributed with this
# repository; request them directly from the IMSGC (https://imsgc.net/).
# The derived gene set is provided at scdrs/MS.gs (see scdrs/README.md).

gwas_file <- file.path(REF_DIR, "MS.final.txt")
if (!file.exists(gwas_file)) {
  warning("GWAS summary statistics not found at ", gwas_file,
          " - skipping the MAGMA input step. See scdrs/README.md.")
} else {
  gwas <- data.table::fread(gwas_file)
  stopifnot(all(c("SNP", "CHR", "BP", "A1", "A2", "P") %in% names(gwas)))
  print(summary(gwas$P))

  out <- gwas[, c("SNP", "P", "N")]
  write.table(out, file.path(WORK_DIR, "MS.final.magma.tsv"),
              sep = '\t', quote = FALSE, row.names = FALSE)
  message("wrote ", file.path(WORK_DIR, "MS.final.magma.tsv"),
          "  (", nrow(out), " SNPs)")
}
