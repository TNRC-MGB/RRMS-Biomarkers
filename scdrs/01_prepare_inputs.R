# ==============================================================================
# (a) Seurat -> h5ad
# ==============================================================================
# scDRS reads raw counts from an AnnData object. Seurat v5 assays do not export
# cleanly, so the RNA assay is converted back to a v3 Assay first, and the
# imputed-ADT assay is dropped

export_h5ad <- function(seu, file_name, dir = WORK_DIR) {
  to_export <- seu
  Seurat::DefaultAssay(to_export) <- "RNA"
  if ("impADT" %in% Seurat::Assays(to_export)) to_export[["impADT"]] <- NULL

  assayv3 <- as(to_export[["RNA"]], "Assay")
  stopifnot(identical(colnames(assayv3), colnames(to_export)))
  to_export[["RNA"]] <- assayv3

  scCustomize::as.anndata(
    x               = to_export,
    file_path       = dir,
    file_name       = paste0(file_name, ".h5ad"),
    assay           = "RNA",
    main_layer      = "counts",
    other_layers    = NULL,
    transer_dimreduc = FALSE,     # (sic - argument is spelled this way upstream)
    verbose         = TRUE
  )
  message("wrote ", file.path(dir, paste0(file_name, ".h5ad")))
}

pbmc <- readRDS(file.path(OBJ_DIR, "pbmc_final.RDS"))
export_h5ad(pbmc, "ms_pbmc")
rm(pbmc); invisible(gc(FALSE))

B <- readRDS(file.path(OBJ_DIR, "B_clean.RDS"))
